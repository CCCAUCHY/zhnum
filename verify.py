#!/usr/bin/env python3
"""zhnum/zhbase locale 验证

zhnum:  首字分区 + 数字数值序 — 全部检查
        核心语义: 位置敏感族键 — N篇(量词篇,序数空) 与 篇N(序数篇,
        量词空) 分族不混排 (篇N 子族在前); 同(序数,量词)族聚族且族内纯
        数值序; **同值写法不等值** — 按值序相邻, 值内按注册序
        (一 < 壹 < 1, 第十章 < 第10章, strcoll ≠ 0)
zhbase: 仅默认排序 — 汉字**单块** (笔画/部首/仓颉/码点, 简繁合并) +
        兼容汉字行 + 脚本行 (中文连块), 只跑默认序检查

首字全局顺序 (zhnum): 拉丁 < 数字(值序) < 汉字(单块) < 兼容汉字 < 其他脚本
  GLib/Nautilus 对 ASCII 数字段自编码 (自然序, 组内 2 < 10 与 locale 无关);
  组的位置 (二级影子): 阿拉伯 < 拉丁 < 数值 < 中文 (阿拉伯最前);
  GLib 层 NFKC 折叠 (gunicollate.c 固有):
  Ａ≡A、①≡'1' 槽文本键、兼容汉字≡正字 — 本验证集不含可折叠字符, 仅记录

双路径: strxfrm (glibc) + GLib utf8_collate_key_for_filename (Nautilus 实际走的路径)

运行: LC_ALL=<zhnum|zhbase>.UTF-8 LOCPATH=<编译目录> python3 verify.py
  (LOCPATH 会遮蔽系统 archive, 必须显式指定)
"""
import locale, os
locale.setlocale(locale.LC_ALL, '')

CUR = os.environ.get('LC_ALL', '') or locale.getlocale()[0] or ''
FULL = 'zhnum' in CUR      # zhnum: 数值槽全检查; zhbase: 只跑默认序检查

import functools
sk = locale.strxfrm

PATHS = [('strxfrm', sk)]
try:
    from gi.repository import GLib
    PATHS.append(('glib-filename', lambda s: GLib.utf8_collate_key_for_filename(s, -1)))
except Exception as e:
    print(f'(GLib 不可用, 仅 strxfrm 路径: {e})')

bad = 0
def check(label, pairs, key):
    global bad
    for a, b, want in pairs:
        got = -1 if key(a) < key(b) else (1 if key(a) > key(b) else 0)
        ok = got == want
        bad += not ok
        print(f'{"✓" if ok else "✗"} {label}: {a} {"<" if got<0 else ("=" if got==0 else ">")} {b}')

def seqcheck(label, names, key, expected=None):
    global bad
    if expected is None: expected = names
    got = sorted(names, key=key)
    ok = got == expected
    bad += not ok
    print(f'{"✓" if ok else "✗"} {label}')
    if not ok:
        for g, e in zip(got, expected):
            if g != e: print(f'    期望 {e}, 得到 {g}')

for name, key in PATHS:
    # 1. 笔画数序 (Unihan kTotalStrokes): zhbase/zhnum 的默认排序
    check(f'笔画数[{name}]', [
        ('乙', '丁', -1), ('丁', '上', -1), ('上', '中', -1), ('中', '后', -1),
        ('级', '言', -1), ('言', '季', -1), ('季', '前', -1),
        ('前', '班', -1), ('班', '章', -1), ('章', '集', -1),
    ], key)

    if not FULL:
        # zhbase 到此为止: 数字字也是普通汉字, 与其他汉字按笔画序比较
        check('zhbase数字字笔画序', [
            ('三', '上', -1), ('零', '乙', 1), ('一', '丁', -1), ('十', '下', -1),
        ], key)
        # zhbase 单块结构 (zhnum 的继承契约): 块内笔画混排;
        # 兼容汉字行在块尾、脚本行在最后 (中文连块)
        check('zhbase简繁合并[笔画混排]', [
            ('丁', '車', -1), ('万', '萬', -1), ('马', '馬', -1), ('龙', '龍', -1),
            ('車', '疆', -1), ('馬', '赢', -1),
        ], key)
        check('zhbase中文连块[脚本在汉字上]', [
            ('章', 'あ', -1), ('章', 'Ω', -1), ('一', 'あ', -1),
        ], key)
        continue

    # 2. 分区: 拉丁 < 汉字 < (兼容) < 脚本行 (阿拉伯不进数值区, 走脚本自然位);
    #    GLib 切 ASCII 数字段自编码 ⇒ 阿拉伯最前
    common = [('a', '乙', -1),
              ('a.txt', '一.txt', -1), ('B.txt', '亿亿.txt', -1),
              ('一', '丁', -1), ('一.txt', '乙', -1),
              ('壹', '乙', -1)]
    if name == 'strxfrm':
        # 阿拉伯走脚本行 ⇒ 汉字块之后 (一 < '1', 零 < '9')
        arab = [('一', '1', -1), ('9', '零', 1)]
    else:
        arab = [('1', '一', -1), ('1', '丁', -1), ('9', '零', -1)]  # GLib 阿拉伯最前
    check(f'分区[{name}]', common + arab, key)

    # 3. 数值序核心 (族内纯数值; 位置分区; 同值写法相邻但不等值)
    core = [
        ('零', '一', -1), ('九', '十', -1), ('一', '一十', -1), ('十一', '一十一', -1),
        ('一', '壹', -1), ('万', '萬', -1),               # 同值相邻, 注册序 (一<壹, 万<萬)
        ('九', '壹', 1), ('拾', '九', 1),               # 纯数值: 壹(1) < 九(9) < 拾(10)
        ('一（下）', '壹', -1), ('亿亿', '壹', 1),       # (下)=0.3 < 壹=1 < 亿亿
        ('拾篇', '九篇', 1),                           # 9篇 < 10篇
        # 序数槽: (上)<(前)<(中)<(下)<(后), 全部介于 零 与 一
        # (同值括号组内按注册序, 不等值)
        ('一（上）', '一（中）', -1), ('一（中）', '一（下）', -1),
        ('一（上）', '一（前）', -1), ('一（下）', '一（后）', -1),
        ('零（下）', '一', -1), ('一（下）', '二', -1),  # 序数值介于 零 与 一
        ('第十章', '第十一章', -1), ('第一章', '第十一章', -1),
        ('第十一章', '第二十章', -1), ('第十一章', '第十二章', -1),
        ('一章', '二章', -1), ('一百', '一百零一', -1),
        ('一万一', '二万', -1), ('十万', '一百万', -1), ('一亿', '九千万', 1),
        ('一百一十一', '一百一十亿', -1), ('万亿', '九千万亿', -1),
        ('亿亿', '九千万亿', 1),                        # 1e16 > 9e15
        ('第二十', '第九十九', -1),
        ('一百万', '一万亿', -1),
        ('上', '中', -1), ('下', '中', -1),
        # 两位数系数元素: 九十九万 整体匹配, 不被拆成 [九十][九万]
        ('九十九万', '一百', 1), ('九十九万九千九百九十九', '一亿', -1),
    ]
    if name == 'strxfrm':
        # 阿拉伯走脚本自然位 ⇒ 多位串逐位比较, '2' > '10'、
        # 第9章 > 第19章、'10' 在 汉字块后 (九 < '10')
        core += [('9', '10', 1), ('99', '100', 1), ('999', '1000', 1),
                 ('第9章', '第19章', 1), ('10', '九', 1),
                 ('第10章', '第十章', -1), ('第19章', '第十九章', -1)]
    else:
        # GLib 数字段自编码: 9 < 10 < 99 < 100 (与 locale 无关);
        # 数字段先行 ⇒ 第10章 < 第十章
        core += [('9', '10', -1), ('99', '100', -1), ('999', '1000', -1),
                 ('第9章', '第19章', -1), ('10', '九', -1),
                 ('第10章', '第十章', -1), ('第19章', '第十九章', -1)]
    # 位置分区: 篇N 子族 < N篇 子族 (骨架先行在前, 两子族不混排)
    core += [('篇十', '一篇', -1), ('篇一十', '一篇', -1), ('篇一千零一', '一篇', -1),
             ('篇七', '篇十', -1)]
    check(f'数值[{name}]', core, key)
    # 同值不等值: 第一章 与 第1章; 跨值 第3章 > 第二章
    # 两路径均 阿拉伯段先行 (strxfrm: 数字一级走脚本位在骨架字后;
    # GLib: 数字段自编码 01… 压过文本键 eX…)
    check(f'数值[{name}]', [
        ('第1章', '第一章', -1),
        ('第3章', '第二章', -1),
    ], key)

    # 3c. 两 + 口语省十式: 两=2 同值组尾 (二 < 贰 < '2' < 两),
    #     两百/两千/两万/两亿/两万亿/两亿亿 (无 两十), 口语三字
    #     A百B/A千B/A万B/A亿B = A*U+B*U/10 (二百五=250/三千六=3600/五万一=
    #     51000/两亿五=2.5e8); 同值组内 口语形排最尾 (二百五十 < '250' < 二百五)。
    #     已知限制 (贪心抢前缀, 见 README 已知边界): 省零读法受扰 —
    #     二千零一 < 两千、二万五十 > 二万一百 (口语元素抢前 3 字)
    check(f'两/口语[{name}]', [
        ('二', '两', -1), ('贰', '两', -1), ('两', '三', -1),
        ('一百九十九', '两百', -1), ('二百', '两百', -1), ('两百', '两百一', -1),
        ('二千', '两千', -1), ('一千九百九十九', '两千', -1), ('两千', '两千一', -1),
        ('二千一', '两千一', -1),
        ('二万', '两万', -1), ('一万九千九百九十九', '两万', -1),
        ('两万', '两万一', -1), ('两万一', '五万', -1),
        ('两亿', '两亿五', -1), ('二亿五', '两亿五', -1), ('两亿五', '三亿', -1),
        ('一万亿', '两万亿', -1), ('两万亿', '三万亿', -1), ('亿亿', '两亿亿', -1),
        ('二百四', '二百五', -1), ('二百五', '二百六', -1),
        ('二百五十', '二百五', -1), ('一百五十', '一百五', -1),
        ('三千五百九十九', '三千六', -1), ('三千六', '三千七', -1),
        ('五万', '五万一', -1), ('五万一', '五万二', -1), ('五万零一', '五万一', -1),
    ], key)

    # 3b. 前后缀混合: 前缀 + 序数 + 量词 + 后缀全模式
    #     册为主序 (数值), v 为次序 (同一册内 v1 < v2);
    #     阿拉伯段先行: 同骨架族内 阿拉伯段 < 汉字段 (第1册 < 第一册)
    check(f'前后缀[{name}]', [
        ('验收文档第一册v1', '验收文档第一册v2', -1),
        ('验收文档第一册v2', '验收文档第二册v1', -1 if name != 'strxfrm' else 1),
        ('验收文档第二册v1', '验收文档第二册v2', -1),
        ('验收文档第1册v2', '验收文档第一册v2', -1),
        ('验收文档第一册', '验收文档第一册v1', -1),
        ('验收文档第一册v2', '验收文档第贰册v1', -1 if name != 'strxfrm' else 1),
    ], key)
    # strxfrm 已知限制: 无切段的 mb 序里 阿拉伯尾缀 vN 一级不透明 ⇒
    # v后缀组整体沉底 (v1 < v2 < … < 无后缀), 组间册序被数字逐位抢先;
    # GLib 切段保护: v 切文本段 N 切数字段自编码 ⇒ 册序优先, v 数值序
    docs = ['验收文档第一册.txt', '验收文档第一册v1.txt', '验收文档第一册v2.txt',
            '验收文档第1册v3.txt', '验收文档第二册.txt', '验收文档第贰册.txt',
            '验收文档第二册v1.txt', '验收文档第三册.txt']
    if name == 'strxfrm':
        expected = ['验收文档第1册v3.txt', '验收文档第一册.txt', '验收文档第二册.txt',
                    '验收文档第贰册.txt', '验收文档第三册.txt', '验收文档第一册v1.txt',
                    '验收文档第二册v1.txt', '验收文档第一册v2.txt']
    else:
        expected = ['验收文档第1册v3.txt', '验收文档第一册.txt', '验收文档第一册v1.txt',
                    '验收文档第一册v2.txt', '验收文档第二册.txt', '验收文档第二册v1.txt',
                    '验收文档第贰册.txt', '验收文档第三册.txt']
    seqcheck(f'前后缀全序[{name}]', docs, key, expected)

    # 4. 量词聚族: 相同量词在一起, 量词本身按默认序 (笔画) 排序
    seqcheck(f'量词聚族[{name}]', ['一级', '二级', '三级', '一班', '二班', '三班'], key,
             ['一级', '二级', '三级', '一班', '二班', '三班'])
    # 回(6画) 组在 章(11画) 组前 (量词按 zhbase 笔画序)
    seqcheck(f'量词默认序[{name}]', ['一章', '二回', '二章', '一回'], key,
             ['一回', '二回', '一章', '二章'])

    # 5. 章节全序: 两族 (第X章 族 与 纯数字 族, '第' 一级权重 → 纯数字族在前)
    names = ['一.txt','二.txt','三.txt','九.txt','十.txt','十一.txt','十九.txt','二十.txt',
             '二十七.txt','三十.txt','九十九.txt','一百.txt','一百零一.txt','一千.txt','一千零一.txt',
             '第一章.txt','第二章.txt','第三章.txt','第九章.txt','第十章.txt','第十一章.txt',
             '第十九章.txt','第二十章.txt','第二十一章.txt','第三十章.txt','第九十九章.txt',
             '第一百章.txt','第一百零一章.txt','第一百一十章.txt','第一百二十章.txt','第二百章.txt',
             '第一千章.txt','第一千零一章.txt']
    seqcheck(f'章节全序[{name}]', names, key)

    # 6. 简繁合并单块: 块内笔画混排;
    #    数字字除外 — 万/億 等已进数值槽等值, 不按笔画
    check(f'简繁合并[{name}]', [
        ('马', '馬', -1), ('车', '車', -1),
        ('丁', '車', -1), ('马', '車', -1), ('车', '馬', -1),
        ('龙', '龍', -1), ('华', '華', -1), ('东', '東', -1),
        ('車', '疆', -1), ('馬', '赢', -1),   # 笔画序: 繁体先于简体是常态
    ], key)

    # 6b. 中文连块: 脚本行在汉字块之上 — 中文区不夹假名/希腊
    #     (GLib 路径兼容字被 NFKC 折叠入块, 脚本仍在上)
    check(f'中文连块[{name}]', [
        ('章', 'あ', -1), ('章', 'Ω', -1), ('万', 'あ', -1),
    ], key)

# 7. 数值两两回归 (仅数值变体, strcoll 路径)
#    同值不同写法**不等值** (独立槽, 按注册序相邻) — 检查 r ≠ 0;
#    跨值严格按数值方向. 同串同名 (列表重复项) 仍 = 0.
if FULL:
    D0 = '零一二三四五六七八九'
    def read(n):
        if n == 0: return ['零', '〇']
        s = str(n); units = ['', '十', '百', '千']
        secs = []
        while s: secs.append(s[-4:]); s = s[:-4]
        sec_units = ['', '万', '亿', '万亿', '亿亿']
        out = ''
        for si in range(len(secs)-1, -1, -1):
            sec = secs[si]; body = ''
            for i, ch in enumerate(sec):
                d = int(ch); pos = len(sec) - 1 - i
                if pos == 0: body += D0[d] if (d or len(sec)==1) else ''
                else:
                    if d == 0:
                        if body and not body.endswith('零'): body += '零'
                    else:
                        if not (d == 1 and pos == 1 and len(sec) == 2 and not body): body += D0[d]
                        body += units[pos]
            # 节内前导零 (如 10001 的个节 '0001'): 补 零 — 一万零一, 不是 一万一
            if body and sec[0] == '0': body = '零' + body
            body = body.rstrip('零')
            if body: out += body + (sec_units[si] if si else '')
        return [out] if out else ['零']

    pairs = []
    for n in list(range(0, 150)) + [999,1000,1001,1010,1050,1100,1101,1999,2000,2005,2010,9999,
         10000,10001,10010,10100,11000,11001,19000,19999,20000,20001,20050,20100,25000,99999,
         100000,100001,100500,101000,10**6,10**6+500,10**7,10**8,10**8+1,10**12,10**12+1,
         10**16,10**16+1,2*10**16,9*10**15]:
        for h in read(n): pairs.append((h, n))
    pairs += [('万亿',10**12),('三萬',30000),('拾万',100000),('十万',100000),('拾萬',100000),
              ('壹佰万',10**6),('一百万',10**6),('九億',9*10**8),('五百萬',5*10**6),
              ('一十',10),('一十一',11),('九万亿',9*10**12),('一百一十亿',110*10**8),
              ('亿亿',10**16),('九千万亿',9*10**15),('一百一十一',111),
              # 阿拉伯数字不注册 — 不参与数值回归 (strxfrm 走脚本自然位)
              # 两+口语三字回归 (两万 安全: 在列 20001/20050/20100 读法全被
              # 3 字元素抢走, 抢到的值均 > 20000 ⇒ 与 两万 相对位置恒正确;
              # 两千 不入 — 二千零一/零五/零一十 含 零 抢不走, 首原子 二千 与
              # 两千 同值早槽 ⇒ 拾万类前缀延伸失败 +3, 语义检查在 3c 覆盖)
              ('两',2),('两百',200),('两亿',2*10**8),('两万亿',2*10**12),('两亿亿',2*10**16),
              ('二百五',250),('三千六',3600),('五万一',51000),('两亿五',25*10**7),
              # 省零四字 X万B十/X万B百/X千B十 (一万一=11000、一万一十=10010、
              # 一万一百=10100、二千一十=2010 — 省零读法均注册为元素)
              ('一万一',11000),('一万一十',10010),('一万一百',10100),
              ('二万一十',20010),('二万一百',20100),('二千一十',2010)]
    import itertools
    n_bad = 0
    for (a, na), (b, nb) in itertools.combinations(pairs, 2):
        r = locale.strcoll(a, b)
        if na == nb:
            good = (r == 0) if a == b else (r != 0)   # 同值写法不等值
        else:
            good = (r < 0) == (na < nb)
        n_bad += not good
    bad += n_bad
    total = len(pairs)*(len(pairs)-1)//2
    print(f'{"✓" if n_bad == 0 else "✗"} 数值两两回归: {total - n_bad}/{total} 对通过')

